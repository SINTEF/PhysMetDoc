# Cached objects
_cache: dict[str, Any] = {}


def get_emmo() -> Triplestore:
    """Return a Triplestore object with EMMO loaded."""
    if "emmo" in _cache:
        return _cache["emmo"]
    ts = Triplestore("rdflib")
    baseurl = f"https://w3id.org/emmo/{EMMO_VERSION}"
    ts.parse(f"{baseurl}#", format="turtle")
    ts.parse(f"{baseurl}/disciplines/units/otherunits-abox", format="turtle")
    _cache["emmo"] = ts
    return ts


EMMO = Namespace(
    "https://w3id.org/emmo#",
    label_annotations=True,
    triplestore=get_emmo(),
    check=True,
)


def get_species_iri(symbol: str) -> str:
    """Return the EMMO IRI corresponding to chemical symbol `symbol`."""
    return EMMO[f"{atomic_names[symbol]}Symbol"]
